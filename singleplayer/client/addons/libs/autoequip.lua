-- Match a spell name against an AshitaCast pattern.
-- Supports * wildcard and | OR separator (e.g. "Cure*|Curaga*").
local function match_name_pattern(pattern, name)
	if name == nil then
		return false;
	end
	local lname = name:lower();
	for part in (pattern .. '|'):gmatch('([^|]+)|') do
		part = part:match('^%s*(.-)%s*$');
		if part ~= '' then
			-- Escape Lua magic chars except *, then convert * -> .*
			local lua_pat = '^' .. part:lower()
				:gsub('([%(%)%.%+%-%?%[%]%^%$%%])', '%%%1')
				:gsub('%*', '.*') .. '$';
			if lname:match(lua_pat) then
				return true;
			end
		end
	end
	return false;
end

-- Strip null terminators that C string bindings sometimes leave in Lua strings.
local function clean_str(s)
	if s == nil then return nil; end
	return (s:gsub('%z', ''));
end

