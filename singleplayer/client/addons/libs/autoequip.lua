-- Apply a parsed XML body to autoequip's in-memory state. Returns true on
-- success, false (with an error logged) when <sets> is missing or parse failed.
local function apply_parsed_body(char_name, job_name, content)
	local root = parse_xml(content or '');
	if root == nil then
		autoutil.log('AutoEquip', 'Failed to parse XML');
		return false;
	end
	local sets_node = nil;
	for _, child in ipairs(root.children) do
		if child.tag == 'sets' then
			sets_node = child;
			break;
		end
	end
	if sets_node == nil then
		autoutil.log('AutoEquip', 'No <sets> element found in XML');
		return false;
	end

	local variables = {};
	for _, child in ipairs(root.children) do
		if child.tag == 'variables' then
			for _, var_node in ipairs(child.children) do
				if var_node.tag == 'var' and var_node.attrs.name then
					variables[var_node.attrs.name] = var_node.text or '0';
				end
			end
		end
	end

	autoequip.xml_root    = root;
	autoequip.sets_node   = sets_node;
	autoequip.variables   = variables;
	autoequip.loaded_char = char_name;
	autoequip.loaded_job  = job_name;
	return true;
end

-- Synchronous server-side fetch over loopback HTTP. Server is the source
-- of truth for configs; the addon no longer reads from the local Ashita
-- install. Invokes callback(success) inline once the response is parsed.
-- The callback is optional — callers that don't care about the result can
-- omit. The signature stays callback-shaped (rather than returning success)
-- to preserve the call sites that already expect to fire continuation work
-- when the load completes (e.g. gear_tab.reload_config rebuilding sets).
function autoequip.load(char_name, job_name, callback)
	autoequip.load_tried = true;
	if char_name == nil or char_name == '' or job_name == nil or job_name == '' then
		if callback then callback(false) end
		return;
	end
	local filename = string.format('%s_%s', char_name, job_name);
	local http     = require('http_client');
	-- Async GET: schedule the fetch, react in the callback once the response
	-- arrives (on a later frame). The main thread isn't blocked, so the
	-- FFXI client keeps pumping keepalives and the UI keeps rendering.
	http.get('/configs/equip/' .. filename, function(code, body, _, err)
		if code == nil then
			autoutil.log('AutoEquip', string.format('HTTP fetch failed for %s: %s', filename, tostring(err)));
			if callback then callback(false) end
			return;
		end
		if code == 404 then
			autoutil.log('AutoEquip', string.format('No equip config on server for %s', filename));
			if callback then callback(false) end
			return;
		end
		if code ~= 200 or body == nil or body == '' then
			autoutil.log('AutoEquip', string.format('Server returned %s for %s', tostring(code), filename));
			if callback then callback(false) end
			return;
		end
		local ok = apply_parsed_body(char_name, job_name, body);
		if ok then
			autoutil.log('AutoEquip', string.format('Loaded %s', filename));
			-- (Gearlock visual lock is now applied server-side on
			-- onGameIn — see modules/singleplayer/bots/ai_equip_swap.lua.
			-- No client-side packet to ship here anymore.)
		end
		if callback then callback(ok) end
	end);
end

-- Mutate the in-memory tree only. Persistence happens via the addon's Save
-- button → 0x180 → server. The in-memory tree is the working copy until the
-- next fetch via autoequip.load.
function autoequip.set_slot(set_name, slot_key, item_name)
	if not autoequip.sets_node then return; end
	local xml_tag = SLOT_XML_TAG[slot_key] or slot_key;
	for _, set_node in ipairs(autoequip.sets_node.children) do
		if set_node.tag == 'set' and set_node.attrs and set_node.attrs.name == set_name then
			local found = false;
			for _, slot_node in ipairs(set_node.children) do
				if slot_node.tag == xml_tag or slot_node.tag == slot_key then
					slot_node.text = item_name or '';
					found = true;
					break;
				end
			end
			if not found and item_name and item_name ~= '' then
				table.insert(set_node.children, {tag=xml_tag, attrs={}, children={}, text=item_name});
			end
			break;
		end
	end
end

-- Remove a slot entry from a set entirely (drops the <head>/<body>/... node
-- from the set's children). Resolution treats a missing slot the same as
-- an empty one, but actually deleting the node keeps the saved XML tidy.
-- No-op when the set or slot doesn't exist.
function autoequip.remove_slot(set_name, slot_key)
	if not autoequip.sets_node then return; end
	local xml_tag = SLOT_XML_TAG[slot_key] or slot_key;
	for _, set_node in ipairs(autoequip.sets_node.children) do
		if set_node.tag == 'set' and set_node.attrs and set_node.attrs.name == set_name then
			for i, slot_node in ipairs(set_node.children) do
				if slot_node.tag == xml_tag or slot_node.tag == slot_key then
					table.remove(set_node.children, i);
					return;
				end
			end
			return;
		end
	end
end

-- Reload the current character/job config (useful after an /autoequip reload command).
function autoequip.reload()
	if autoequip.loaded_char and autoequip.loaded_job then
		autoequip.load_tried = false;
		autoequip.load(autoequip.loaded_char, autoequip.loaded_job);
	end
end

-- Attempt to load the config for the currently logged-in character if not already loaded.
-- Called automatically by every public equip function.
local function ensure_loaded()
	if autoequip.xml_root ~= nil then
		return;
	end
	if autoequip.load_tried then
		return;
	end

	-- Edit-target aware: honor the dropdown override if set.
	local char_name, job_name = autoequip.get_edit_target();
	if not char_name or char_name == '' or not job_name or job_name == '' then
		autoequip.load_tried = true;
		return;
	end

	autoequip.load(char_name, job_name);
end

-- Find a top-level section node (e.g. 'premagic', 'midmagic') in the loaded XML.
local function get_section(name)
	if autoequip.xml_root == nil then
		return nil;
	end
	for _, child in ipairs(autoequip.xml_root.children) do
		if child.tag == name then
			return child;
		end
	end
	return nil;
end

