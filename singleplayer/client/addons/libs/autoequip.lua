function autoequip.equip_set(set_name)
	ensure_loaded();
	if autoequip.xml_root == nil then
		autoutil.log('AutoEquip', 'set: xml not loaded');
		return;
	end
	if autoequip.sets_node == nil then
		autoutil.log('AutoEquip', 'set: no sets node');
		return;
	end
	local gear = resolve_set(autoequip.sets_node, set_name, {});
	if next(gear) == nil then
		autoutil.log('AutoEquip', string.format('set: unknown set "%s"', set_name));
		return;
	end
	local changed = send_equip_packets(gear);
	if next(changed) ~= nil then
		autoutil.log('AutoEquip', string.format('set %s: %s', set_name, format_changed(changed)));
	end
end

autoequip.resolve_set = resolve_set;

function autoequip.handle_command(args)
	if args[1] ~= '/autoequip' then return false; end
	-- Only claim subcommands the lib actually owns. Anything else (show, reload,
	-- nil, ...) falls through so the addon's own handler can run — without this,
	-- /autoequip show was getting eaten by the usage-line branch below.
	if args[2] == 'set' and args[3] ~= nil then
		autoequip.equip_set(args[3]);
		return true;
	end
	return false;
end

-- Expose the serializer for tabs that need to ship the whole document back
-- to the server via PUT /configs/equip/<file>. Indentation matches what
-- the server wrote (the original load path), so a fetch → no-op-edit →
-- save round-trip is byte-stable.
autoequip.serialize_node = serialize_node;
autoequip.parse_xml      = parse_xml;

-- Serialize the entire in-memory XML document into a string suitable for
-- the body of a PUT. Returns nil if no file is loaded. The XML declaration
-- line matches the one the legacy server-side set_subtree_equip writer
-- used, so existing files won't churn header bytes on first save.
function autoequip.serialize_full()
    if autoequip.xml_root == nil then return nil; end
    return '<?xml version="1.0" encoding="utf-8" standalone="yes"?>\n'
         .. serialize_node(autoequip.xml_root, 0);
end

return autoequip;
