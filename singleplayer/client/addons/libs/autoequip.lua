-- ============================================================
-- XML serializer (used by save/set_slot)
-- Note: comments and blank lines in the original XML are not preserved after save.
-- ============================================================

local function serialize_node(node, depth)
	depth = depth or 0;
	local ind = string.rep('\t', depth);
	local attr_parts = {};
	if node.attrs then
		for k, v in pairs(node.attrs) do
			table.insert(attr_parts, k .. '="' .. tostring(v) .. '"');
		end
		table.sort(attr_parts);
	end
	local attr_str = #attr_parts > 0 and (' ' .. table.concat(attr_parts, ' ')) or '';

	if #node.children > 0 then
		local out = { ind .. '<' .. node.tag .. attr_str .. '>' };
		for _, child in ipairs(node.children) do
			table.insert(out, serialize_node(child, depth + 1));
		end
		table.insert(out, ind .. '</' .. node.tag .. '>');
		return table.concat(out, '\n');
	elseif node.text and node.text ~= '' then
		return ind .. '<' .. node.tag .. attr_str .. '>' .. node.text .. '</' .. node.tag .. '>';
	else
		return ind .. '<' .. node.tag .. attr_str .. '/>';
	end
end

