-- Build a player_info table from live game data.
local function build_player_info()
	local party      = AshitaCore:GetDataManager():GetParty();
	local player     = AshitaCore:GetDataManager():GetPlayer();
	local entity_mgr = AshitaCore:GetDataManager():GetEntity();
	local player_idx = party:GetMemberTargetIndex(0);
	local status_id  = entity_mgr:GetStatus(player_idx);

	local status_str;
	if     status_id == 1              then status_str = 'engaged';
	elseif status_id == 33             then status_str = 'resting';
	elseif status_id == 2 or status_id == 3 then status_str = 'dead';
	else                                    status_str = 'idle';
	end

	local mainJobIdx = party:GetMemberMainJob(0);
	local subJobIdx  = party:GetMemberSubJob(0);
	local mainJobStr = autoutil.jobs[mainJobIdx] and autoutil.jobs[mainJobIdx]:lower() or 'unknown';
	local subJobStr  = autoutil.jobs[subJobIdx]  and autoutil.jobs[subJobIdx]:lower()  or '';
	local jobStr     = subJobStr ~= '' and (mainJobStr .. '/' .. subJobStr) or mainJobStr;

	-- Party / alliance counts and target membership
	local pt_count = 0;
	local a_count  = 0;
	for i = 0, 5 do
		local nm = party:GetMemberName(i);
		if nm and nm ~= '' then pt_count = pt_count + 1; end
	end
	for i = 0, 17 do
		local nm = party:GetMemberName(i);
		if nm and nm ~= '' then a_count = a_count + 1; end
	end

	-- Current selected target info
	local tgt_api  = AshitaCore:GetDataManager():GetTarget();
	local tgt_idx  = tgt_api:GetTargetIndex();
	local tgt_sid  = tgt_api:GetTargetServerId();
	local tgt_ent  = (tgt_idx ~= nil and tgt_idx ~= 0) and GetEntity(tgt_idx) or nil;
	local t_hpp, t_distance, t_id, t_index, t_name, t_type;
	local pt_target, a_target = false, false;
	if tgt_ent ~= nil then
		t_hpp      = tgt_ent.HealthPercent;
		t_distance = math.sqrt(tgt_ent.Distance);
		t_id       = tgt_sid;
		t_index    = tgt_idx;
		t_name     = clean_str(tostring(tgt_ent.Name or ''));
		local flags = tgt_ent.SpawnFlags;
		if     bit.band(flags, 0x0200) ~= 0 then t_type = 'self';
		elseif bit.band(flags, 0x0001) ~= 0 then t_type = 'pc';
		elseif bit.band(flags, 0x0002) ~= 0 then t_type = 'npc';
		elseif bit.band(flags, 0x0010) ~= 0 then t_type = 'monster';
		else                                      t_type = 'unknown'; end
		for i = 0, 5 do
			if party:GetMemberServerId(i) == tgt_sid then
				pt_target = true; a_target = true; break;
			end
		end
		if not a_target then
			for i = 6, 17 do
				if party:GetMemberServerId(i) == tgt_sid then a_target = true; break; end
			end
		end
	end

	-- Pet info (via player entity's PetTargetIndex)
	local self_ent = GetEntity(player_idx);
	local pet_ent  = (self_ent and self_ent.PetTargetIndex ~= 0) and GetEntity(self_ent.PetTargetIndex) or nil;
	local pet_active, pet_hpp, pet_status_str, pet_name, pet_distance;
	if pet_ent then
		pet_active = 'true';
		pet_hpp    = pet_ent.HealthPercent;
		pet_name   = clean_str(tostring(pet_ent.Name or ''));
		pet_distance = math.sqrt(pet_ent.Distance);
		local ps = pet_ent.Status;
		if     ps == 1              then pet_status_str = 'engaged';
		elseif ps == 33             then pet_status_str = 'resting';
		elseif ps == 2 or ps == 3  then pet_status_str = 'dead';
		else                             pet_status_str = 'idle'; end
	else
		pet_active = 'false';
	end

	return {
		-- Player numeric
		hp          = party:GetMemberCurrentHP(0),
		hpp         = party:GetMemberCurrentHPP(0),
		mp          = party:GetMemberCurrentMP(0),
		mpp         = party:GetMemberCurrentMPP(0),
		tp          = party:GetMemberCurrentTP(0),
		hpmax       = player:GetHealthMax(),
		mpmax       = player:GetManaMax(),
		joblevel    = party:GetMemberMainJobLevel(0),
		subjoblevel = party:GetMemberSubJobLvl(0),
		attack      = player:GetAttack(),
		defense     = player:GetDefense(),
		fireresist      = player:GetResist(0),
		iceresist       = player:GetResist(1),
		windresist      = player:GetResist(2),
		earthresist     = player:GetResist(3),
		lightningresist = player:GetResist(4),
		waterresist     = player:GetResist(5),
		lightresist     = player:GetResist(6),
		darkresist      = player:GetResist(7),
		-- Player string
		status  = status_str,
		mainjob = mainJobStr,
		subjob  = subJobStr,
		job     = jobStr,
		name    = clean_str(tostring(party:GetMemberName(0) or '')),
		-- Party / alliance
		pt_count   = pt_count,
		a_count    = a_count,
		pt_inparty = pt_count > 1 and 'true' or 'false',
		a_inally   = a_count > 6  and 'true' or 'false',
		pt_target  = pt_target and 'true' or 'false',
		a_target   = a_target  and 'true' or 'false',
		-- Target
		t_hpp      = t_hpp,
		t_distance = t_distance,
		t_id       = t_id,
		t_index    = t_index,
		t_name     = t_name,
		t_type     = t_type,
		-- Pet
		pet_active   = pet_active,
		pet_hpp      = pet_hpp,
		pet_status   = pet_status_str,
		pet_name     = pet_name,
		pet_distance = pet_distance,
	};
end

local EQUIP_BY_ID_OPCODE    = 0x173;
local EQUIP_BY_ID_RESULT    = 0x174;

-- Entries sent in the most recent 0x173 packet; committed to last_gear on 0x174 response.
local pending_equip = nil;

-- Send a single 0x173 equip-by-id packet for all slots whose item has changed.
-- The server searches its own authoritative inventory for each item ID, so no
-- client-side inventory walk is needed.  last_gear is NOT updated here; it is
-- updated when the 0x174 response arrives (success or failure).
-- Returns a table of slot->item for every slot queued in the packet.
local function send_equip_packets(gear)
	local changed = {};
	local entries = {};
	local res_mgr = AshitaCore:GetResourceManager();

	-- If body is changing, clear head from last_gear so it gets re-sent.
	-- Some body pieces block the head slot; the server silently rejects the head
	-- equip packet while they're on, leaving last_gear out of sync with reality.
	if gear['body'] ~= nil and gear['body'] ~= autoequip.last_gear['body'] then
		autoequip.last_gear['head'] = nil;
	end

	for slot_name, item_name in pairs(gear) do
		if autoequip.last_gear[slot_name] ~= item_name then
			local slot_id = SLOT_IDS[slot_name];
			if slot_id ~= nil then
				local res = res_mgr:GetItemByName(item_name, 1);
				if res then
					table.insert(entries, { item_id = res.ItemId, slot_id = slot_id, slot_name = slot_name, item_name = item_name });
				else
					autoutil.log('AutoEquip', string.format('Unknown item: "%s" (slot: %s)', item_name, slot_name));
				end
			else
				autoutil.log('AutoEquip', string.format('Unknown slot name: "%s"', slot_name));
			end
		end
	end

	if #entries == 0 then return changed; end

	-- Body MUST be sorted first so the server processes it before head.
	-- Some body pieces set m_EquipBlock on the head slot (e.g. certain capes/mantles
	-- that visually replace the head model).  The server processes entries in array
	-- order, so if head arrives before body the head equip hits the old body's
	-- m_EquipBlock state and may succeed or fail incorrectly.  By guaranteeing body
	-- is entry[1] we ensure the new body's block state is established before head
	-- is evaluated.  main(0) < sub(1) already sorts correctly by slot_id ascending,
	-- so body is the only slot that needs an explicit priority override.
	table.sort(entries, function(a, b)
		local pa = (a.slot_id == SLOT_IDS.body) and 0 or 1;
		local pb = (b.slot_id == SLOT_IDS.body) and 0 or 1;
		if pa ~= pb then return pa < pb; end
		return a.slot_id < b.slot_id;
	end);

	-- Build 0x173 packet: 4-byte header + 4-byte (count + padding) + up to 16 x 4-byte entries
	local count = math.min(#entries, 16);
	local bytes  = {};
	for i = 1, 4 + 4 + 16 * 4 do bytes[i] = 0; end
	bytes[1] = 0x73; bytes[2] = 0x01;  -- opcode 0x173 LE
	bytes[5] = count;
	for i = 1, count do
		local base = 8 + (i - 1) * 4;
		local e    = entries[i];
		bytes[base + 1] = e.item_id % 256;
		bytes[base + 2] = math.floor(e.item_id / 256) % 256;
		bytes[base + 3] = e.slot_id;
	end

	pending_equip = entries;
	AddOutgoingPacket(EQUIP_BY_ID_OPCODE, bytes);

	-- Return the queued slots so callers know what was attempted.
	for i = 1, count do
		changed[entries[i].slot_name] = entries[i].item_name;
	end
	return changed;
end

-- Result codes from 0x174 response (mirror server-side enum in 0x174_equip_by_id_result.h)
local EQUIP_RESULT_SUCCESS  = 0;
local EQUIP_RESULT_NOTFOUND = 1;
local EQUIP_RESULT_BLOCKED  = 2;
local EQUIP_RESULT_NOOP     = 3;

function autoequip.on_incoming_packet(id, size, data)
	if id ~= EQUIP_BY_ID_RESULT then return false; end
	if pending_equip == nil then return false; end

	local ok, err = xpcall(function()
		-- Packet body: byte 5 = Count, bytes 6-8 = padding, bytes 9+ = Results[0..Count-1]
		local count = struct.unpack('B', data, 5);

		for i = 1, math.min(count, #pending_equip) do
			local e      = pending_equip[i];
			local result = struct.unpack('B', data, 8 + i);

			-- Server processed this entry regardless of outcome; update last_gear so we
			-- don't re-send it next tick.  The only exception would be NOTFOUND, but
			-- we still record it to avoid hammering the server for a missing item.
			autoequip.last_gear[e.slot_name] = e.item_name;

			if result == EQUIP_RESULT_NOTFOUND then
				autoutil.log('AutoEquip', string.format('Item not found: "%s" (slot: %s)', e.item_name, e.slot_name));
			elseif result == EQUIP_RESULT_BLOCKED then
				autoutil.log('AutoEquip', string.format('Equip blocked by game mechanic: "%s" -> %s', e.item_name, e.slot_name));
			end
			-- EQUIP_RESULT_SUCCESS (0) and EQUIP_RESULT_NOOP (3) need no log.
		end

		pending_equip = nil;
	end, debug.traceback);
	if not ok then autoutil.log('AutoEquip', 'on_incoming_packet error: ' .. tostring(err)); end
	return false;
end

local function format_changed(changed)
	local parts = {};
	for slot, item in pairs(changed) do
		table.insert(parts, slot .. '=' .. item);
	end
	table.sort(parts);
	return #parts > 0 and table.concat(parts, ', ') or 'none';
end

local EMPTY_SPELL_INFO = {id=nil, name=nil, type=nil, skill_name=nil, element=nil, recast=nil, casttime=nil, mpcost=nil, mpaftercast=nil, mppaftercast=nil};

local function equip_section(section_name, spell_info)
	ensure_loaded();
	if autoequip.xml_root == nil then
		autoutil.log('AutoEquip', string.format('%s: xml not loaded (char=%s)', section_name, tostring(autoequip.loaded_char)));
		return;
	end
	local section = get_section(section_name);
	if section == nil then
		autoutil.log('AutoEquip', string.format('%s: section not found in xml', section_name));
		return;
	end
	local gear = process_section(section, spell_info, build_player_info(), autoequip.sets_node, autoequip.variables);
	local changed = send_equip_packets(gear);
	autoequip.current_section = section_name;
	if next(changed) ~= nil then
		autoutil.log('AutoEquip', string.format('%s changed: %s', section_name, format_changed(changed)));
	end
end

