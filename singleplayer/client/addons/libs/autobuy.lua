local function load_prices()
    local f = io.open(CSV_PATH, 'r');
    if not f then autoutil.log('AutoBuy', string.format('WARNING: could not open price CSV: %s', CSV_PATH)); return; end
    local count = 0; local first = true;
    for line in f:lines() do
        if first then first = false;
        else
            local fields = {};
            for field in line:gmatch('([^,]+)') do table.insert(fields, field:match('^%s*(.-)%s*$')); end
            local id = tonumber(fields[1]);
            local sell_single = fields[3] == '1';
            local sell_stacks = fields[7] == '1';
            if id and (sell_single or sell_stacks) then
                prices[id] = {
                    price_single = tonumber(fields[5])  or 0,
                    stock_single = tonumber(fields[6])  or 0,
                    price_stacks = tonumber(fields[9])  or 0,
                    stock_stacks = tonumber(fields[10]) or 0,
                    sell_single  = sell_single,
                    sell_stacks  = sell_stacks,
                };
                count = count + 1;
            end
        end
    end
    f:close();
    autoutil.log('AutoBuy', string.format('Loaded %d price entries from CSV.', count));
end

local function load_recipes()
    local ok, result = pcall(dofile, RECIPES_FILE);
    if not ok or type(result) ~= 'table' then
        autoutil.log('AutoBuy', 'WARNING: could not load recipes.lua: ' .. tostring(result)); return;
    end
    recipes_by_key = result;
    local count = 0; for _ in pairs(recipes_by_key) do count = count + 1; end
    autoutil.log('AutoBuy', string.format('Loaded %d recipe keys.', count));
end

local function load_aliases()
    local f = io.open(ALIASES_FILE, 'r');
    if not f then return; end
    local raw = f:read('*a'); f:close();
    local ok, data = pcall(function() return JSON:decode(raw); end);
    if ok and type(data) == 'table' then aliases = data; end
end

local function load_groups()
    local handle = io.popen(string.format('dir /b "%s*.json" 2>nul', GROUPS_DIR));
    if not handle then return; end
    local count = 0;
    for filename in handle:lines() do
        local path = GROUPS_DIR .. filename;
        local f = io.open(path, 'r');
        if f then
            local raw = f:read('*a'); f:close();
            local ok, data = pcall(function() return JSON:decode(raw); end);
            if ok and type(data) == 'table' then
                local entry = { name = data.name, list = data.list or {} };
                local keys = { (data.name or ''):lower() };
                if type(data.aliases) == 'table' then
                    for _, alias in ipairs(data.aliases) do table.insert(keys, alias:lower()); end
                end
                for _, key in ipairs(keys) do groups_by_key[key] = entry; end
                count = count + 1;
            end
        end
    end
    handle:close();
    autoutil.log('AutoBuy', string.format('Loaded %d group file(s).', count));
end

local function get_price(item_id, is_stack)
    local entry = prices[item_id];
    if not entry then return nil, false; end
    if is_stack then return entry.price_stacks, entry.sell_stacks;
    else return entry.price_single, entry.sell_single; end
end

local function strip_variant_suffix(s)
    local base, v = s:match('^(.+)%s+v(%d+)$');
    if base then return base, tonumber(v); end
    return s, nil;
end

local function resolve_recipe(name)
    local key = name:lower();
    if recipes_by_key[key] then return key, recipes_by_key[key], nil; end
    local aliased = aliases[key];
    if aliased then
        local alias_key, alias_variant = strip_variant_suffix(aliased:lower());
        if recipes_by_key[alias_key] then return alias_key, recipes_by_key[alias_key], alias_variant; end
    end
    return nil, nil, nil;
end

local function resolve_purchases(item_id, items_needed, prefer_stack)
    local e = prices[item_id];
    if not e then return nil; end
    local stacks_avail  = e.sell_stacks and e.stock_stacks or 0;
    local singles_avail = e.sell_single and e.stock_single or 0;
    local function stack_group(n) return { is_stack=true,  count=n, price=e.price_stacks }; end
    local function single_group(n) return { is_stack=false, count=n, price=e.price_single }; end
    if prefer_stack then
        local stacks_needed = math.ceil(items_needed / 12);
        if stacks_avail >= stacks_needed then return { stack_group(stacks_needed) }; end
        local items_from_stacks = stacks_avail * 12;
        local singles_needed    = items_needed - items_from_stacks;
        if singles_avail < singles_needed then return nil; end
        local result = {};
        if stacks_avail > 0 then table.insert(result, stack_group(stacks_avail)); end
        table.insert(result, single_group(singles_needed));
        return result;
    else
        if items_needed >= 4 and stacks_avail > 0 then
            local stacks_needed = math.ceil(items_needed / 12);
            if stacks_avail >= stacks_needed then return { stack_group(stacks_needed) }; end
            local items_from_stacks = stacks_avail * 12;
            local singles_needed    = items_needed - items_from_stacks;
            if singles_avail >= singles_needed then
                local result = {};
                table.insert(result, stack_group(stacks_avail));
                if singles_needed > 0 then table.insert(result, single_group(singles_needed)); end
                return result;
            end
        end
        if singles_avail >= items_needed then return { single_group(items_needed) }; end
        local remaining = items_needed - singles_avail;
        local stacks_needed = math.ceil(remaining / 12);
        if stacks_avail >= stacks_needed then
            local result = {};
            if singles_avail > 0 then table.insert(result, single_group(singles_avail)); end
            table.insert(result, stack_group(stacks_needed));
            return result;
        end
        return nil;
    end
end

local function item_display_name(item_id)
    local res = AshitaCore:GetResourceManager():GetItemById(item_id);
    if res and res.Name then
        local n = tostring(res.Name[0]):gsub('%z', '');
        if n ~= '' then return n; end
    end
    return 'id=' .. tostring(item_id);
end

local function find_item_id_by_name(name)
    local res = AshitaCore:GetResourceManager():GetItemByName(name, 0);
    if res then return res.ItemId; end
    return nil;
end

local function find_available_recipe(variants, is_stack, quantity)
    for _, recipe in ipairs(variants) do
        local valid = true; local purchases = {};
        local yield = recipe.qty or 1;
        local synths = math.ceil(quantity / yield);
        local needed = {}; local order = {};
        for _, id in ipairs(recipe.ingredients) do
            if not needed[id] then needed[id] = 0; table.insert(order, id); end
            needed[id] = needed[id] + 1;
        end
        for _, item_id in ipairs(order) do
            local groups = resolve_purchases(item_id, needed[item_id] * synths, is_stack);
            if not groups then valid = false; break; end
            local name = item_display_name(item_id);
            for _, g in ipairs(groups) do
                table.insert(purchases, { name=name, item_id=item_id, is_stack=g.is_stack, count=g.count, price=g.price });
            end
        end
        if valid then return recipe, purchases, synths; end
    end
    return nil, nil, nil;
end

local function find_partial_recipe(recipe, is_stack, quantity)
    if not recipe then return nil, {}, 0; end
    local purchases = {};
    local yield = recipe.qty or 1;
    local synths = math.ceil(quantity / yield);
    local needed = {}; local order = {};
    for _, id in ipairs(recipe.ingredients) do
        if not needed[id] then needed[id] = 0; table.insert(order, id); end
        needed[id] = needed[id] + 1;
    end
    for _, item_id in ipairs(order) do
        local groups = resolve_purchases(item_id, needed[item_id] * synths, is_stack);
        if groups then
            local name = item_display_name(item_id);
            for _, g in ipairs(groups) do
                table.insert(purchases, { name=name, item_id=item_id, is_stack=g.is_stack, count=g.count, price=g.price });
            end
        end
    end
    return recipe, purchases, synths;
end

local function free_inventory_slots()
    local inv = AshitaCore:GetDataManager():GetInventory();
    local max = inv:GetContainerMax(0);
    local used = 0;
    for i = 0, max do
        local item = inv:GetItem(0, i);
        if item and item.Id ~= 0 then used = used + 1; end
    end
    return max - used;
end

