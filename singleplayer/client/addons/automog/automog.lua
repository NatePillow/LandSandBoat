    -- Stats grid. Format mirrors the client UI: "STR  12  +4".
    autoutil.section_head('Stats');
    imgui.Dummy(0, 2);
    -- HP / MP first, each on its own row, above the primary stats.
    imgui.TextColored(0.85, 0.85, 0.85, 1.0,
        string.format('HP  %d / %d', prof.hp_cur or 0, prof.hp_max or 0));
    imgui.TextColored(0.85, 0.85, 0.85, 1.0,
        string.format('MP  %d / %d', prof.mp_cur or 0, prof.mp_max or 0));
    imgui.Dummy(0, 4);
    for _, k in ipairs(STAT_KEYS) do
        local base  = (prof.stat_base or {})[k]  or 0;
        local bonus = (prof.stat_bonus or {})[k] or 0;
        local sign  = (bonus >= 0) and '+' or '';
        imgui.Text(string.format('%-4s %3d  %s%d', k, base, sign, bonus));
    end
    imgui.Dummy(0, 4);
    -- Combat stats, each on its own row. Labels are all 3 chars, so the
    -- '%-4s' field left-aligns them and the values line up in a column.
    local combat_rows = {
        { 'Atk', prof.atk }, { 'Def', prof.def },
        { 'Acc', prof.acc }, { 'Eva', prof.eva },
    };
    for _, r in ipairs(combat_rows) do
        imgui.TextColored(0.85, 0.85, 0.85, 1.0,
            string.format('%-4s %d', r[1], r[2] or 0));
    end

    inv_sep();

    -- Equipment list. Each row: small [x] Button on the LEFT for unequip
    -- (only when the slot has an item; empty rows pad with a 22-px Dummy
    -- so the slot text stays aligned), then a Selectable that focuses
    -- the slot and switches the right column to an item picker. Mirrors
    -- the autoequip Gear-tab slot layout. Server-side 0x171 with
    -- ItemId=0 = unequip (charutils::UnequipItem on the named slot).
    -- Skills — combat first, then magic. Capped skills render blue, matching
    -- vanilla FFXI's skill display. Only skills the char actually has (value>0)
    -- are shown, so the list reflects the job. (The equipped-items list moved to
    -- the autoequip "Current" tab.)
    local skills = prof.skills or {};
    local function skill_col(title, list)
        autoutil.section_head(title);
        imgui.Dummy(0, 2);
        local any = false;
        for _, sk in ipairs(list) do
            local s = skills[sk[1]];
            if s and s.value > 0 then
                any = true;
                local row = string.format('%-10s %d', sk[2] .. ':', s.value);
                if s.capped then
                    imgui.TextColored(0.4, 0.7, 1.0, 1.0, row); -- capped = blue
                else
                    imgui.Text(row);
                end
            end
        end
        if not any then imgui.TextDisabled('  (none)'); end
    end
    skill_col('Combat Skills', COMBAT_SKILLS);
    imgui.Dummy(0, 4);
    skill_col('Magic Skills', MAGIC_SKILLS);

    imgui.Unindent(STATUS_LEFT_PAD);
end

-- Send EQUIP_BOT_ITEM (0x171). Wire body: 4-byte header + 16 CharName +
-- 2 ItemId + 1 SlotId + 1 padding = 24 bytes total. Server validates the
-- target char is the requester themselves OR a headless owned by them,
-- finds the item across all equip-bearing containers, calls
-- charutils::EquipItem, then pushes a fresh 0x1A8 CHAR_PROFILE so the
-- addon's char_profile_cache picks up the new equipment.
--
-- Same packet for primary AND headless — the server-side handler treats
-- both uniformly. This replaces the vanilla 0x173 EQUIP_BY_ID path for
-- the Status tab picker because 0x173 has no target-char field so it
-- couldn't be reused for cross-char headless equip.
-- Assigns to the forward-declared local above draw_status_profile.
-- Using `function name(...)` syntax (without `local`) would create a
-- global; plain assignment binds to the existing local instead.
local function draw_status_tab()
    -- Same width as the inventory tab for parity / no jumpiness on swap.
    local col_w = 260;

    if selected_char == nil or selected_char == '' then
        imgui.TextDisabled('No character selected.');
        return;
    end

    -- Kick a fetch the first time this tab paints for the current char.
    -- ensure() is a no-op if the cache already has a profile.
    char_profile_cache.ensure(selected_char);
    local prof = char_profile_cache.get(selected_char);

    imgui.BeginChild('##status_left', col_w, 0, false);
    if prof == nil then
        imgui.Dummy(0, 8);
        imgui.TextDisabled('Loading profile...');
    else
        draw_status_profile(col_w, prof);
    end
    imgui.EndChild();

    imgui.SameLine(0, 30);

    imgui.BeginChild('##status_right', col_w, 0, false);
    -- Equipment editing moved to the autoequip "Current" tab; the right column
    -- now always shows the gil / delivery / scrolls / change-job block.
    draw_inv_right_static(col_w);
    imgui.EndChild();
end

-- Right-column item detail card. Mirrors autoequip's confirm panel layout —
-- centered name, dim level/count, equippable jobs in chunked rows, then the
-- resource-manager Description wrapped across the column. We read the entry
-- back out of the inv_cache by (bag, slot) instead of trusting whatever name
-- the focused click captured, so it stays in sync with a snapshot refresh.
local function draw_inv_item_detail(col_w, bag_id, slot)
    if slot == nil then
        imgui.SetCursorPosX(math.max(0, (col_w - calc_text_w('Select an item to view details.')) / 2));
        imgui.TextDisabled('Select an item to view details.');
        return;
    end

    local bag   = inv_cache_lib.get_bag(selected_char, bag_id);
    local entry = bag and bag[slot];
    if not entry or entry.id == 0 or entry.count == 0 then
        imgui.SetCursorPosX(math.max(0, (col_w - calc_text_w('Select an item to view details.')) / 2));
        imgui.TextDisabled('Select an item to view details.');
        return;
    end

    local res_mgr = AshitaCore:GetResourceManager();
    local res     = res_mgr:GetItemById(entry.id);
    local name    = (res and res.Name) and tostring(res.Name[0]):gsub('%z', '') or ('item#' .. entry.id);
    local level   = (res and res.Level) or 0;
    local jobs    = (res and res.Jobs) or 0;
    local desc    = (res and res.Description and res.Description[0]) and tostring(res.Description[0]):gsub('%z', '') or '';
    local stack_sz = (res and res.StackSize) or 1;
    local count   = entry.count or 0;

    -- Name centered. White text (not the dim "section header" color) so it
    -- reads as the actual title of the panel.
    imgui.SetCursorPosX(math.max(0, (col_w - calc_text_w(name)) / 2));
    imgui.TextColored(1.0, 1.0, 1.0, 1.0, name);

    -- Subtitle: level + count (dim, centered)
    local subtitle = {};
    if level and level > 0 then table.insert(subtitle, 'Lv.' .. level); end
    if stack_sz > 1 then
        table.insert(subtitle, string.format('%d / %d', count, stack_sz));
    elseif count > 1 then
        table.insert(subtitle, 'x' .. count);
    end
    if #subtitle > 0 then
        local sub = table.concat(subtitle, '   ');
        imgui.SetCursorPosX(math.max(0, (col_w - calc_text_w(sub)) / 2));
        imgui.TextDisabled(sub);
    end

    -- Jobs that can equip. 0 == none (consumable / scroll). 0xFFFFFFFF == any.
    if jobs ~= 0 and jobs ~= 0xFFFFFFFF then
        local jnames = {};
        for i, jname in ipairs(autoutil.jobs) do
            if bit.band(jobs, bit.lshift(1, i)) ~= 0 then
                table.insert(jnames, jname);
            end
        end
        if #jnames > 0 then
            imgui.Dummy(0, 8);
            local row = {};
            for idx, jname in ipairs(jnames) do
                table.insert(row, jname);
                if #row == 6 or idx == #jnames then
                    local line = table.concat(row, ' ');
                    imgui.SetCursorPosX(math.max(0, (col_w - calc_text_w(line)) / 2));
                    imgui.TextDisabled(line);
                    row = {};
                    if idx < #jnames then imgui.Dummy(0, 2); end
                end
            end
        end
    end

    if desc ~= '' then
        imgui.Dummy(0, 8);
        imgui.Separator();
        imgui.Dummy(0, 6);
        imgui.TextWrapped(desc);
    end
end

local function draw_inventory_tab()
    local col_w = 260;

    local bag_items = get_bag_items(inv_tab_bag);
    local sel_count = 0;
    for _ in pairs(inv_tab_selected) do sel_count = sel_count + 1; end
    local has_sel = sel_count > 0;
    local can_drop = has_sel and inv_tab_bag == 0;

    -- Drop a stale focused slot if the item is gone (sort, drop, transfer).
    if inv_tab_focused ~= nil then
        local still_present = false;
        for _, item in ipairs(bag_items) do
            if item.slot == inv_tab_focused then still_present = true; break; end
        end
        if not still_present then inv_tab_focused = nil; end
    end

    -- Left: bag selector + multi-select item list
    imgui.BeginChild('##inv_left', col_w, 0, false);
    local new_bag = draw_bag_selector('inv', inv_tab_bag);
    if new_bag ~= inv_tab_bag then
        inv_tab_bag      = new_bag;
        inv_tab_selected = {};
        inv_tab_focused  = nil;
    end
    imgui.Separator();
    imgui.Dummy(0, 6);
    imgui.TextDisabled(string.format('%d / %d slots', #bag_items, get_container_max(inv_tab_bag)));
    imgui.Dummy(0, 6);
    imgui.BeginChild('##inv_ilist', 0, 0, false);
    for _, item in ipairs(bag_items) do
        local is_sel = inv_tab_selected[item.slot] == true;
        if imgui.Selectable(item.name .. '##invi_' .. item.slot, is_sel) then
            -- A click both (a) toggles selection state (multi-select stays as-is)
            -- and (b) sets focus for the right-column detail panel so even
            -- deselecting still rests focus on what was just clicked.
            if is_sel then inv_tab_selected[item.slot] = nil;
            else inv_tab_selected[item.slot] = true; end
            inv_tab_focused = item.slot;
        end
        if item.stack_size > 1 then
            imgui.SameLine();
            imgui.TextDisabled('(' .. item.count .. ')');
        end
    end
    if #bag_items == 0 then imgui.TextDisabled('(empty)'); end
    imgui.EndChild();
    imgui.EndChild();

    imgui.SameLine(0, 30);

    -- Right: focused-item detail card, then Trade + Drop when items are selected.
    -- The static gil/sort/delivery/scrolls/change-job block was moved to the
    -- Status tab — that's a per-char "always visible" home and frees this
    -- column to be about the item the user is actually looking at.
    imgui.BeginChild('##inv_right', col_w, 0, false);
    draw_inv_item_detail(col_w, inv_tab_bag, inv_tab_focused);

    if has_sel then
        local avail_w = imgui.GetContentRegionAvailWidth();

        -- Trade section
        inv_sep();
        imgui.SetCursorPosX((avail_w - calc_text_w('Trade')) / 2);
        autoutil.section_head('Trade');
        imgui.Spacing();
        local trade_btn_w = math.floor((avail_w - 2 * FAV_GAP) / 3);
        local party     = AshitaCore:GetDataManager():GetParty();
        -- Exclude the currently-displayed char (you can't trade to yourself).
        -- Was using primary name regardless of char selection, so switching the
        -- char selector left the wrong row excluded.
        local self_name = selected_char or ((party and party:GetMemberName(0)) or '');
        -- party:GetMemberName(i) returns trusts alongside PCs and there's no
        -- v3 API to tell them apart. Use the server-authoritative PC roster
        -- (0x186 → autoutil.alliance_pcs) as the source of truth so trust
        -- buttons don't pollute the trade row.
        local pc_set = {};
        for _, m in ipairs(autoutil.alliance_pcs or {}) do
            if m.name and m.name ~= '' then pc_set[m.name] = true; end
        end
        if next(pc_set) == nil and self_name ~= '' then
            -- Roster hasn't synced yet — allow self at minimum so the trade
            -- block doesn't read as broken on a cold cache.
            pc_set[self_name] = true;
        end
        local col_idx = 0;
        for i = 0, 17 do
            local name = (party and party:GetMemberName(i)) or '';
            if name ~= '' and name ~= self_name and pc_set[name] then
                if col_idx % 3 ~= 0 then imgui.SameLine(0, FAV_GAP); end
                if imgui.Button(name .. '##trd_' .. i, trade_btn_w, 0) then
                    local trade_items = {};
                    for slot, _ in pairs(inv_tab_selected) do
                        table.insert(trade_items, { bag = inv_tab_bag, slot = slot });
                    end
                    if #trade_items > 0 then
                        send_item_trade(self_name, name, trade_items);
                        inv_tab_selected = {};
                    end
                end
                col_idx = col_idx + 1;
            end
        end
        if col_idx == 0 then
            imgui.SetCursorPosX((avail_w - calc_text_w('No other members.')) / 2);
            imgui.TextDisabled('No other members.');
        end

        -- Drop section
        inv_sep();
        local drop_w = imgui.GetWindowWidth();
        imgui.SetCursorPosX((drop_w - calc_text_w('Drop Items')) / 2);
        autoutil.section_head('Drop Items');
        imgui.Spacing();
        local ds_w   = calc_text_w('Drop Selected') + 16;
        local dat_w  = calc_text_w('Drop All Of Type') + 16;
        local row_w  = ds_w + 8 + dat_w;
        imgui.SetCursorPosX(math.floor((drop_w - row_w) / 2));
        if not can_drop then imgui.PushStyleVar(ImGuiStyleVar_Alpha, 0.35); end
        if imgui.Button('Drop Selected##invds', ds_w, 0) and can_drop then
            local bag0    = inv_cache_lib.get_bag(0);
            local entries = {};
            for slot, _ in pairs(inv_tab_selected) do
                local e = bag0[slot];
                if e and e.id ~= 0 and e.count > 0 then
                    local res = AshitaCore:GetResourceManager():GetItemById(e.id);
                    local n   = res and res.Name and tostring(res.Name[0]):gsub('%z','') or ('item#'..e.id);
                    table.insert(entries, { index = slot, count = e.count, name = n });
                end
            end
            if #entries > 0 then autodrop.queue_drops(entries); end
        end
        imgui.SameLine(0, 8);
        if imgui.Button('Drop All Of Type##invdat', dat_w, 0) and can_drop then
            local bag0     = inv_cache_lib.get_bag(0);
            local seen_ids = {};
            local entries  = {};
            for slot, _ in pairs(inv_tab_selected) do
                local e = bag0[slot];
                if e and e.id ~= 0 and not seen_ids[e.id] then
                    seen_ids[e.id] = true;
                    for s, se in pairs(bag0) do
                        if se.id == e.id and se.count > 0 then
                            local res = AshitaCore:GetResourceManager():GetItemById(se.id);
                            local n   = res and res.Name and tostring(res.Name[0]):gsub('%z','') or ('item#'..se.id);
                            table.insert(entries, { index = s, count = se.count, name = n });
                        end
                    end
                end
            end
            if #entries > 0 then autodrop.queue_drops(entries); end
        end
        if not can_drop then imgui.PopStyleVar(); end
    end

    imgui.EndChild();
end

