        imgui.SameLine(ZONE_X);
        imgui.TextColored(0.7, 0.85, 1.0, 1.0, tostring(e.zone or '?'));

        if clicked then
            if nm_expanded[mobid] then
                nm_expanded[mobid] = nil;
            else
                nm_expanded[mobid] = true;
                -- Lazy-fetch drops on first expand. Cached forever (until
                -- tab leave / addon reload) since drop tables are static.
                if nm_drops[mobid] == nil and not nm_drops_loading[mobid] then
                    nm_drops_loading[mobid] = true;
                    http_client.get('/nms/' .. tostring(mobid) .. '/drops', function(code, body)
                        nm_drops_loading[mobid] = nil;
                        if code ~= 200 or type(body) ~= 'string' or body == '' then
                            nm_drops[mobid] = {};
                            return;
                        end
                        local ok, parsed = pcall(json.decode, json, body);
                        nm_drops[mobid] = (ok and type(parsed) == 'table') and parsed or {};
                    end);
                end
            end
        end

        -- Drops sub-list (when expanded). Loading placeholder if the
        -- fetch hasn't landed; "No drops." if the response was empty.
        if nm_expanded[mobid] then
            if nm_drops[mobid] == nil then
                imgui.SameLine(NAME_X);
                imgui.Dummy(0, 0);
                imgui.TextDisabled('   Loading drops...');
            elseif #nm_drops[mobid] == 0 then
                imgui.TextDisabled('   No drops.');
            else
                local res_mgr = AshitaCore:GetResourceManager();
                for _, d in ipairs(nm_drops[mobid]) do
                    local res     = res_mgr:GetItemById(d.itemId);
                    local nm      = (res and res.Name) and tostring(res.Name[0]):gsub('%z', '') or ('item#' .. d.itemId);
                    local percent = (d.rate or 0) / 10.0;
                    imgui.TextDisabled(string.format('   %5.1f%%  %s', percent, nm));
                end
            end
        end
    end
    if #rows == 0 then
        imgui.TextDisabled('No NMs match.');
    end
    imgui.EndChild();
end

