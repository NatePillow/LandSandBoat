            for _, m in ipairs(roster) do
                if m.name ~= primary_name then
                    if imgui.Selectable(m.name) then pick(m.name); end
                    listed = listed + 1;
                end
            end
            if listed == 0 then imgui.TextDisabled('(no other sessioned chars)') end
            imgui.EndPopup();
        end
    end
    imgui.Separator();
    transfer_right_bag = draw_bag_selector('tr', transfer_right_bag, right_char);
    imgui.Separator();
    imgui.Dummy(0, 10);
    imgui.TextDisabled(string.format('%d / %d slots', #right_items, get_container_max(transfer_right_bag, right_char)));
    imgui.Dummy(0, 10);
    imgui.BeginChild('##xfr_rlist', 0, 0, false);
    for _, item in ipairs(right_items) do
        imgui.Text(item.name);
        if item.stack_size > 1 then
            imgui.SameLine();
            imgui.TextDisabled('(' .. item.count .. ')');
        end
    end
    if #right_items == 0 then imgui.TextDisabled('(empty)'); end
    imgui.EndChild();
    imgui.EndChild();
end

