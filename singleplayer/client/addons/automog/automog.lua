local function poll_statuses()
    local function check(source, text, char_name)
        if text ~= state.prev_statuses[source] then
            state.prev_statuses[source] = text;
            state.push_status(source, text, char_name);
        end
    end
    local buy = autobuy.state;
    local buy_text = state.has_status(buy.status) and
        (buy.current_name and buy.current_name ~= ''
            and (buy.status .. ' (' .. buy.current_name .. ')')
            or buy.status)
        or buy.status;
    -- Box-pull tags its char when it was triggered on a non-primary
    -- (task #111 stores the target_name on autobox.state). Transfer reads
    -- the right-side char when set, otherwise the row was intra-char.
    check('Box',      autobox.state.status, autobox.state.target_name);
    check('Buy',      buy_text);
    check('Sell',     autosell.state.status);
    check('Drop',     autodrop.state.status);
    check('Craft',    autocraft.state.status);
    check('Scrolls',  autoscroll.state.status);
    -- Either side can now drive cross-char; surface whichever override is
    -- set (right takes precedence if both, matching the destination-is-meaningful
    -- convention used by the Box badge).
    check('Transfer', state.transfer_status, state.transfer_right_char or state.transfer_left_char);
end

ashita.register_event('render', function()
    -- Advance pending HTTP coroutines (NM Hunter fetches go through this).
    -- See libs/http_client.lua header: each addon must call tick() once per
    -- frame from its OWN render hook, otherwise non-blocking requests
    -- never make progress.
    http_client.tick();
    autodrop.on_render();
    autosell.on_render();
    autocraft.on_render();
    autobuy.on_render();
    poll_statuses();

    -- On UI open transition: lazily ensure the selected char's inventory is
    -- loaded. ensure_inventory is a no-op when the cache is already warm,
    -- so re-opening the UI later in the session is instant. Use the Reload
    -- Inventory button for a force refresh.
    local cur_ui = ui_open ~= nil and imgui.GetVarValue(ui_open) or false;
    if cur_ui and not prev_ui_open and state.selected_char and state.selected_char ~= '' then
        inv_cache_lib.ensure_inventory(state.selected_char);
    end
    prev_ui_open = cur_ui;

    if ui_open == nil or not cur_ui then return; end

    -- Fixed initial size with manual resize handles - NOT AlwaysAutoResize.
    -- AlwaysAutoResize fights nested BeginChild(W, 0) panes: those rely on
    -- a parent-imposed remaining-height to fill, but auto-resize makes the
    -- parent wait on the children's content size, which collapses the
    -- inner lists to a tiny default and clips long content (item lists,
    -- history rows, etc.).
    --
    -- Height tuned to fit the Status tab's left column without scrolling:
    --   name + identity (3 rows) + exp                          ~ 80 px
    --   sep + Stats label + 7 stats + HP/MP/Atk/Def             ~190 px
    --   sep + Equipment label + 16 slot rows                    ~340 px
    -- Plus window chrome (title bar + char selector + Reload row +
    -- tab strip + padding) ~130 px = ~740 px content + chrome → 840 px
    -- gives a margin so font-size variance doesn't push the bottom
    -- equipment rows under the resize handle. History tab's width
    -- floor (Dummy(620, 0)) still pins horizontal consistency. User
    -- can drag to resize.
    imgui.SetNextWindowSize(640, 840, ImGuiSetCond_FirstUseEver);
    autoutil.push_solid_window_bg();
    if not imgui.Begin('AutoMog', ui_open) then
        imgui.End();
        autoutil.pop_solid_window_bg();
        return;
    end

    -- Char selector dropdown (task #109). Far-left of the tab row. Drives the
    -- state.selected_char used by all read-paths (Inventory tab bag display,
    -- Transfer tab side caps, etc.). Source: sessioned PCs returned by
    -- 0x186 ALLIANCE_PC_LIST (the server's alliance walk inherently excludes
    -- offline / unsessioned chars). Action paths still target primary until
    -- tasks #110–#113 land — a banner below the tab row makes that explicit.
    do
        local party        = AshitaCore:GetDataManager():GetParty();
        local primary_name = (party and party:GetMemberName(0)) or '';
        if not state.char_selector_bootstrapped then
            autoutil.send_list_alliance_pcs();
            state.char_selector_bootstrapped = true;
        end
        if state.selected_char == nil and primary_name ~= '' then
            state.selected_char = primary_name;
            inv_cache_lib.ensure_inventory(state.selected_char);
            autoutil.send_get_job_info(primary_name);
        end

        local label = (state.selected_char ~= nil and state.selected_char ~= '') and state.selected_char or 'Pick char';
        if imgui.Button(label .. '##automog_char_pick', 160, 0) then
            autoutil.send_list_alliance_pcs();
            imgui.OpenPopup('##automog_char_pick_popup');
        end
        if imgui.BeginPopup('##automog_char_pick_popup') then
            local function pick(name)
                if name ~= state.selected_char then
                    state.selected_char = name;
                    -- Lazy: only fetch if we don't already have a cached
                    -- inventory for this char. Swapping between previously
                    -- viewed chars is now instant. Use the Reload Inventory
                    -- button (or any path that calls send_inv_request) for
                    -- an explicit refresh.
                    inv_cache_lib.ensure_inventory(name);
                    -- Fire a job-info fetch for the picked char so the
                    -- "Change Job" section in the Inventory tab has fresh
                    -- unlocked-mask + per-job levels to cycle through.
                    autoutil.send_get_job_info(name);
                    -- Profile for the Status tab. ensure() is debounced
                    -- so this is a no-op when the cache is already warm.
                    char_profile_cache.ensure(name);
                end
                imgui.CloseCurrentPopup();
            end
            if primary_name ~= '' and imgui.Selectable(primary_name .. ' (you)') then pick(primary_name) end
            imgui.Separator();
            local roster = autoutil.alliance_pcs or {};
            local listed = 0;
            for _, m in ipairs(roster) do
                if m.name ~= primary_name then
                    if imgui.Selectable(m.name) then pick(m.name); end
                    listed = listed + 1;
                end
            end
            if listed == 0 then imgui.TextDisabled('(no other sessioned chars)') end
            imgui.EndPopup();
        end
        -- Reload refreshes everything the window shows for the selected char:
        -- inventory, the Status-tab profile (stats / equipment / exp / etc. via
        -- char_profile_cache), and job info. Uses .request() (forced) so a warm
        -- cache is bypassed. Anchored to the right edge of the char-picker row.
        local reload_btn_w = C.calc_text_w('Reload') + 8;
        imgui.SameLine(imgui.GetWindowWidth() - reload_btn_w - 8);
        if imgui.Button('Reload##tabs') then
            C.send_inv_request();
            char_profile_cache.request(state.selected_char);
            autoutil.send_get_job_info(state.selected_char);
        end
    end

    for i, tab in ipairs(TABS) do
        if i > 1 then imgui.SameLine(); end
        local is_active = (tab == active_tab);
        if is_active then imgui.PushStyleColor(ImGuiCol_Button, 0.26, 0.59, 0.98, 1.0); end
        if imgui.Button(tab) then
            active_tab = tab;
        end
        if is_active then imgui.PopStyleColor(); end
    end
    imgui.Separator();

    -- Header line: which char is being displayed. Actions (Transfer / AH /
    -- Craft / Drop) now route cross-char to this same selected char server-side
    -- -- 0x194 transfer, 0x19A synth, and /ah/* each resolve the target by name
    -- behind an ownership check -- so the old "actions route to primary" caveat
    -- is gone. Shown for primary too so the header height matches across chars.
    do
        local party        = AshitaCore:GetDataManager():GetParty();
        local primary_name = (party and party:GetMemberName(0)) or '';
        local shown        = (state.selected_char ~= nil and state.selected_char ~= '') and state.selected_char or primary_name;
        if shown ~= '' then
            imgui.TextDisabled(string.format('[Display: %s]', shown));
        end
    end

    imgui.Dummy(0, 3);
    if inv_cache_lib.is_loading(state.selected_char) then
        local dots = string.rep('.', math.floor(autoutil.get_ms_since_epoch() / 1000) % 4);
        imgui.Text('Loading Inventory' .. dots);
    else
        local status_str = state.latest_status and string.format('[%s] %s', state.latest_status.source, state.latest_status.text) or '';
        imgui.TextDisabled(status_str);
    end
    imgui.Dummy(0, 3);
    imgui.Separator();

    local draw_fn = TAB_DRAW[active_tab];
    if draw_fn then draw_fn(); end

    imgui.End();
    autoutil.pop_solid_window_bg();
end);
