local function race_label(race) return (RACE_INFO[race or -1] or { name = '?' }).name; end
local function gender_label(race) return (RACE_INFO[race or -1] or { gender = '?' }).gender; end

-- Resolve a job byte -> short code via autoutil's table. autoutil.jobs is
-- 1-indexed so we offset.
local function job_short(jobId)
    if jobId == nil or jobId == 0 then return '---'; end
    return (autoutil.jobs and autoutil.jobs[jobId]) or string.format('J%d', jobId);
end

-- Look up an item name via Ashita's resource manager. Falls back to
-- "#<id>" when the resource isn't available so the layout never goes
-- blank on an unknown item.
local item_name_cache = {};
local function item_name_for(itemId)
    if itemId == nil or itemId == 0 then return ''; end
    local cached = item_name_cache[itemId];
    if cached ~= nil then return cached; end
    local resmgr = AshitaCore:GetResourceManager();
    local name = string.format('#%d', itemId);
    if resmgr ~= nil then
        local ok, item = pcall(function() return resmgr:GetItemById(itemId); end);
        if ok and item ~= nil and item.Name then
            -- Ashita resource Name is a 0-indexed string array; element 0
            -- carries the English name and needs a NUL strip because the
            -- underlying char[] is padded.
            local n = tostring(item.Name[0]):gsub('%z', '');
            if n ~= '' then name = n; end
        end
    end
    item_name_cache[itemId] = name;
    return name;
end

