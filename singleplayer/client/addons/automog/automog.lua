local AH_CAT_QUERY_OPCODE  = 0x16F;
local AH_CAT_RESULT_OPCODE = 0x170;
-- Custom singleplayer-fork cross-char transfer packets (task #110, consolidated #233).
-- 0x194 AUTOMOG_TRANSFER carries src/dst char names + bag/slot list so the
-- Transfer tab can move between any two sessioned chars owned by the primary.
-- Inventory-tab "Send to <PC>" now also rides 0x194 (src=self bag → dst=PC's
-- LOC_INVENTORY) since every trade target in singleplayer is owned by sender.
-- The retired packets are: 0x16B BULKXFER (was never fired by this addon —
-- intra-char moves go through 0x194 directly), 0x171 ITEM_TRADE.
local AUTOMOG_TRANSFER_OPCODE = 0x194;
local AUTOMOG_TRANSFER_RESULT = 0x195;
