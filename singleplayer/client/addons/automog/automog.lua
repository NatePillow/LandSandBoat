autocraft.get_slots = function(item_id)
    local results = {};
    for slot, entry in pairs(inv_cache_lib.get_bag(0)) do
        if entry.id == item_id and entry.count > 0 then
            table.insert(results, { slot = slot, count = entry.count });
        end
    end
    return results;
end;



ashita.register_event('incoming_packet', function(id, size, data)
    if id == 0x150 then autoutil.check_for_server_ident(id, size, data); return false; end
    if id == 0x152 then autoutil.check_for_relay(id, size, data); return false; end
    if id == 0x186 then autoutil.check_for_alliance_pc_list(id, size, data); return false; end
    if id == 0x19F then autoutil.check_for_job_info(id, size, data); return false; end
    if id == 0x19D then autoutil.check_for_change_job_result(id, size, data); return false; end
    if id == 0x163 then autoutil.check_for_change_look_result(id, size, data); return false; end
    if char_profile_cache.on_incoming_packet(id, size, data) then return false; end

    if inv_cache_lib.on_incoming_packet(id, size, data) then
        -- 0x020 / 0x01E live entirely in the cache; they also drive
        -- autodrop/autobuy state, so dispatch to them after the cache
        -- update so their views are consistent.
        if id == 0x020 then
            autodrop.on_incoming_packet(id, size, data);
            autobuy.on_incoming_packet(id, size, data);
        elseif id == 0x01E then
            autodrop.on_incoming_packet(id, size, data);
        end
        return false;
    end
    if id == AUTOMOG_TRANSFER_RESULT then
        local result = struct.unpack('B', data, 5);
        local moved  = struct.unpack('B', data, 6);
        if result == 0 then
            state.transfer_status = string.format('Transferred %d item(s)', moved);
        elseif result == 1 then
            state.transfer_status = string.format('Partial: %d moved (destination full)', moved);
        else
            state.transfer_status = 'Transfer failed';
        end
        -- After a cross-char move, both src and dst cached inventories are
        -- stale. Re-fetch the two participating chars so the Transfer tab
        -- (and any other tabs reading their bags) reflect the new state.
        if id == AUTOMOG_TRANSFER_RESULT and moved > 0 then
            local left_char  = state.transfer_left_char  or state.selected_char;
            local right_char = state.transfer_right_char or state.selected_char;
            if left_char and left_char ~= '' then inv_cache_lib.send_inv_request(left_char); end
            if right_char and right_char ~= '' and right_char ~= left_char then
                inv_cache_lib.send_inv_request(right_char);
            end
        end
        return false;
    end
    if id == AH_CAT_RESULT_OPCODE then
        -- GP_SERV_COMMAND_AH_CAT_RESULT: PacketData at byte 5
        -- [0]=CatId, [1]=Offset, [2]=Count, [3]=IsLast, [4..]=Entries (8 bytes each: u16 ItemId, u16 Count, u32 MinPrice)
        local cat_id  = struct.unpack('B', data, 5);
        local count   = struct.unpack('B', data, 7);
        local is_last = struct.unpack('B', data, 8);
        if not state.ah_cat_cache[cat_id] then
            state.ah_cat_cache[cat_id] = { items={}, complete=false };
        end
        local entry   = state.ah_cat_cache[cat_id];
        local res_mgr = AshitaCore:GetResourceManager();
        -- Entry size grew from 8 → 12 bytes when we split MinPrice into
        -- separate single/stack fields (server packet 0x170 — without the
        -- split, stack buys quoted the single-listing per-unit price, which
        -- under-bids the stack listing and silently fails server-side).
        for i = 0, count - 1 do
            local base             = 9 + i * 12;
            local item_id          = struct.unpack('H', data, base);
            local single_count     = struct.unpack('B', data, base + 2);
            local stack_count      = struct.unpack('B', data, base + 3);
            local min_single_price = struct.unpack('I', data, base + 4);
            local min_stack_price  = struct.unpack('I', data, base + 8);
            local res   = res_mgr:GetItemById(item_id);
            local name  = '';
            local level = 0;
            local jobs  = 0;
            local stats = {};
            local slots = 0;
            if res then
                if res.Name and res.Name[0] then
                    name = tostring(res.Name[0]):gsub('%z', '');
                end
                level = res.Level or 0;
                jobs  = res.Jobs  or 0;
                slots = res.Slots or 0;
                if res.Description and res.Description[0] then
                    stats = parse_item_stats(tostring(res.Description[0]):gsub('%z', ''));
                end
            end
            if name == '' then name = string.format('Item %d', item_id); end
            table.insert(entry.items, {
                id=item_id, name=name, single_count=single_count, stack_count=stack_count,
                min_single_price=min_single_price, min_stack_price=min_stack_price,
                level=level, jobs=jobs, stats=stats, slots=slots,
                stack_size = (res and res.StackSize or 1),
            });
        end
        if is_last == 1 then
            table.sort(entry.items, function(a, b)
                if a.level ~= b.level then return a.level < b.level; end
                return a.name < b.name;
            end);
            entry.complete = true;
            state.ah_browse_requesting = false;
        end
        return false;
    end
    autobox.on_incoming_packet(id, size, data);
    autoscroll.on_incoming_packet(id, size, data);
    autobuy.on_incoming_packet(id, size, data);
    autosell.on_incoming_packet(id, size, data);
    autocraft.on_incoming_packet(id, size, data);
    autodrop.on_incoming_packet(id, size, data);
    return false;
end);

local function slice(args, from)
    local t = {};
    for i = from, #args do t[#t + 1] = args[i]; end
    return t;
end

ashita.register_event('command', function(cmd, nType)
    local args  = cmd:args();
    local first = args[1] and args[1]:lower() or '';
    if first ~= '/automog' then return false; end

    local sub = args[2] and args[2]:lower() or '';
    -- Bare `/automog` (no args) and `/automog show` toggle the UI the same way
    -- `/automog ui` does. Matches the convention used by /autoequip, /autolot,
    -- /autodps, etc.
    if sub == 'ui' or sub == '' or sub == 'show' then
        if ui_open ~= nil then
            imgui.SetVarValue(ui_open, not imgui.GetVarValue(ui_open));
        end
    elseif sub == 'box'     then autobox.retrieve(state.selected_char);
    elseif sub == 'scrolls' then autoscroll.learn();
    elseif sub == 'drop' then
        local sargs = slice(args, 3);
        if sargs[1] == 'stop' then
            autodrop.on_command({'stop'});
        elseif sargs[1] ~= nil then
            local item_name = table.concat(sargs, ' ', 1);
            local slots = C.find_inv_slots_by_name(item_name);
            if #slots == 0 then
                autoutil.log('AutoDrop', 'No items found matching: ' .. item_name);
            else
                autodrop.queue_drops(slots);
            end
        else
            autoutil.log('AutoDrop', 'Usage: /automog drop <item name>  |  /automog drop stop');
        end
    elseif sub == 'sell' then
        local sargs = slice(args, 3);
        if sargs[1] == 'stop' then
            autosell.on_command({'stop'});
        elseif #sargs >= 3 then
            local quantity  = tonumber(sargs[#sargs]);
            local mode      = sargs[#sargs - 1]:lower();
            local item_name = table.concat(sargs, ' ', 1, #sargs - 2);
            if not quantity or quantity < 1 then
                autoutil.log('AutoSell', 'Invalid quantity.');
            elseif mode ~= 'single' and mode ~= 'stack' then
                autoutil.log('AutoSell', 'Mode must be single or stack.');
            else
                local slots = C.find_inv_slots_by_name(item_name);
                if #slots == 0 then
                    autoutil.log('AutoSell', 'No items found matching: ' .. item_name);
                else
                    autosell.queue_sells(slots, mode == 'stack', quantity);
                end
            end
        else
            autoutil.log('AutoSell', 'Usage: /automog sell <item name> single|stack <quantity>');
        end
    elseif sub == 'craft'   then autocraft.on_command(slice(args, 3));
    elseif sub == 'buy'     then autobuy.on_command(slice(args, 3));
    else
        autoutil.log('AutoMog', 'Usage: /automog ui|box|scrolls|drop|sell|craft|buy [args]');
    end
    return true;
end);

local STAT_MULTI = {
    { 'Accuracy', 'ACC' }, { 'Attack', 'ATK' }, { 'Evasion', 'EVA' },
    { 'Ranged Accuracy', 'RACC' }, { 'Ranged Attack', 'RATK' },
    { 'Magic Accuracy', 'MACC' }, { 'Magic Evasion', 'MEVA' },
    { 'Magic Attack Bonus', 'MAB' }, { 'Magic Defense Bonus', 'MDB' },
    { 'Store TP', 'STP' }, { 'Subtle Blow', 'SB' },
    { 'Double Attack', 'DA' }, { 'Triple Attack', 'TA' },
    { 'Crit hit rate', 'Crit' }, { 'Haste', 'Haste' }, { 'Enmity', 'Enmity' },
};

parse_item_stats = function(desc)
    local s = {};
    if not desc or desc == '' then return s; end
    local def = desc:match('DEF:%s*(%d+)');
    if def then s['DEF'] = tonumber(def); end
    local dmg = desc:match('[Dd]amage:%s*(%d+)');
    if dmg then s['DMG'] = tonumber(dmg); end
    local dly = desc:match('[Dd]elay:%s*(%d+)');
    if dly then s['DLY'] = tonumber(dly); end
    for _, pair in ipairs(STAT_MULTI) do
        local sign, val = desc:match(pair[1] .. '([%+%-])(%d+)');
        if sign and val then s[pair[2]] = tonumber(val) * (sign == '-' and -1 or 1); end
    end
    for stat, sign, val in desc:gmatch('([A-Z][A-Z%d]+)([%+%-])(%d+)') do
        if not s[stat] then s[stat] = tonumber(val) * (sign == '-' and -1 or 1); end
    end
    return s;
end


